//! Questions an agent asks the user through the `ask_user` tool.
//!
//! The gateway publishes a [`UserPrompt`] in the conversation and the run
//! waits until a trusted client answers it with
//! [`Command::AnswerPrompt`](crate::Command::AnswerPrompt). Asking grants
//! nothing: an answer is text returned to the model, never an approval.
use crate::Id;
use serde::{Deserialize, Serialize};

/// Longest question, in characters.
pub const MAX_QUESTION: usize = 2000;
/// Most suggested answers a question may offer.
pub const MAX_CHOICES: usize = 8;
/// Longest suggested answer, in characters.
pub const MAX_CHOICE: usize = 200;
/// Longest free-text answer, in characters.
pub const MAX_ANSWER: usize = 4000;

/// A question waiting for the user's answer.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct UserPrompt {
    /// Generated by the gateway; never shown to the model.
    pub id: Id,
    /// The `ask_user` call that asked it.
    pub call: String,
    pub question: String,
    /// Suggested answers, in the agent's order.
    pub choices: Vec<String>,
    /// Whether the user may answer in their own words.
    pub other: bool,
    pub requested_at: u64,
}

/// The user's reply to a [`UserPrompt`].
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum PromptAnswer {
    /// One of the suggested answers, by position.
    Choice {
        index: u32,
    },
    Text {
        text: String,
    },
    /// The user chose not to answer; the agent is told so.
    Decline,
}

/// How a question ended.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum PromptOutcome {
    Answered,
    Declined,
    /// The run was cancelled or ended before the user answered.
    Expired,
}

/// Why an answer does not fit its question.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum AnswerError {
    #[error("choose one of the {count} suggested answers")]
    NoSuchChoice { count: usize },
    #[error("this question only accepts one of its suggested answers")]
    TextNotAccepted,
    #[error("an answer cannot be empty")]
    Empty,
    #[error("answers are limited to {MAX_ANSWER} characters")]
    TooLong,
}

impl UserPrompt {
    /// Check `answer` against this question, so a client can explain a
    /// mistake before sending and the gateway refuses the same mistakes.
    pub fn check(&self, answer: &PromptAnswer) -> Result<(), AnswerError> {
        match answer {
            PromptAnswer::Choice { index } => {
                if usize::try_from(*index).is_ok_and(|index| index < self.choices.len()) {
                    Ok(())
                } else {
                    Err(AnswerError::NoSuchChoice {
                        count: self.choices.len(),
                    })
                }
            }
            PromptAnswer::Text { .. } if !self.other => Err(AnswerError::TextNotAccepted),
            PromptAnswer::Text { text } if text.trim().is_empty() => Err(AnswerError::Empty),
            PromptAnswer::Text { text } if text.chars().count() > MAX_ANSWER => {
                Err(AnswerError::TooLong)
            }
            PromptAnswer::Text { .. } | PromptAnswer::Decline => Ok(()),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn prompt(choices: usize, other: bool) -> UserPrompt {
        UserPrompt {
            id: Id::new_v4(),
            call: Id::new_v4().to_string(),
            question: Id::new_v4().to_string(),
            choices: (0..choices).map(|_| Id::new_v4().to_string()).collect(),
            other,
            requested_at: 0,
        }
    }

    #[test]
    fn answers_must_fit_the_question() {
        let closed = prompt(2, false);
        assert_eq!(closed.check(&PromptAnswer::Choice { index: 1 }), Ok(()));
        assert_eq!(
            closed.check(&PromptAnswer::Choice { index: 2 }),
            Err(AnswerError::NoSuchChoice { count: 2 })
        );
        assert_eq!(
            closed.check(&PromptAnswer::Text { text: "x".into() }),
            Err(AnswerError::TextNotAccepted)
        );
        assert_eq!(closed.check(&PromptAnswer::Decline), Ok(()));

        let open = prompt(0, true);
        assert_eq!(
            open.check(&PromptAnswer::Choice { index: 0 }),
            Err(AnswerError::NoSuchChoice { count: 0 })
        );
        assert_eq!(
            open.check(&PromptAnswer::Text { text: " \n".into() }),
            Err(AnswerError::Empty)
        );
        assert_eq!(
            open.check(&PromptAnswer::Text {
                text: "é".repeat(MAX_ANSWER)
            }),
            Ok(())
        );
        assert_eq!(
            open.check(&PromptAnswer::Text {
                text: "é".repeat(MAX_ANSWER + 1)
            }),
            Err(AnswerError::TooLong)
        );
    }
}
