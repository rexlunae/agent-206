//! Tool calls, their per-conversation permissions and user approvals.
//!
//! The model may *request* a tool call. Whether it runs is decided by the
//! gateway from the user's per-tool permission, the tool host's own policy and
//! the conversation's capability grant; an `Ask` call additionally waits for a
//! [`Command::ResolveApproval`](crate::Command::ResolveApproval) from a trusted
//! client. Nothing here lets an agent approve its own request.
use crate::{Capability, ErrorReport, Id};
use serde::{Deserialize, Serialize};
use std::collections::BTreeSet;

/// How a tool may run in one conversation, ordered from most to least
/// restrictive so that combining policies is [`Ord::min`].
#[derive(
    Debug, Clone, Copy, Default, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize,
)]
#[serde(rename_all = "snake_case")]
pub enum ToolPermission {
    /// Never offered to the model; a call is refused.
    #[default]
    Deny,
    /// Each call waits for the user's approval of that exact call.
    Ask,
    /// Calls run without asking, within the conversation's grants.
    Allow,
}
impl ToolPermission {
    pub const ALL: [Self; 3] = [Self::Deny, Self::Ask, Self::Allow];
    pub fn label(self) -> &'static str {
        match self {
            Self::Deny => "Deny",
            Self::Ask => "Ask",
            Self::Allow => "Allow",
        }
    }
}

/// How much tool work one run (one user message) may do before it stops.
/// These are the user's limits on this conversation, not model facts.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct ToolBudget {
    /// Model requests per run, the first one included.
    pub rounds: u32,
    /// Tool calls the gateway decides on per run, across all rounds.
    pub tool_calls: u32,
}
impl ToolBudget {
    /// The largest budget the gateway accepts for either limit.
    pub const MAX: u32 = 256;
}
impl Default for ToolBudget {
    fn default() -> Self {
        Self {
            rounds: 8,
            tool_calls: 32,
        }
    }
}

/// Where one tool call is in its lifecycle.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ToolCallState {
    /// Requested by the model; no decision yet.
    Requested,
    /// Waiting for the user to approve or deny it.
    AwaitingApproval,
    Running,
    Succeeded,
    /// The tool, its host or its arguments failed.
    Failed,
    /// Policy or the user refused it; it did not run.
    Denied,
    /// The run was cancelled or stopped before the call finished.
    Cancelled,
    /// Not run because it repeated an earlier call in the same response.
    Skipped,
}
impl ToolCallState {
    /// The call will not change any more.
    pub fn is_final(self) -> bool {
        !matches!(
            self,
            Self::Requested | Self::AwaitingApproval | Self::Running
        )
    }
}

/// One tool call requested by the model, with its outcome.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ToolCall {
    /// The provider's call ID, or one the gateway generated when it was
    /// missing or repeated.
    pub id: String,
    /// `id` was generated by the gateway, so it is not sent back to
    /// providers that match results by their own IDs.
    #[serde(default)]
    pub generated_id: bool,
    /// The model-facing tool name.
    pub tool: String,
    /// The arguments as the JSON object text that runs (after healing), or
    /// the bounded raw text when it could not be parsed.
    pub arguments: String,
    /// Binds approvals to this exact tool name and argument text.
    pub digest: String,
    /// The arguments were repaired before they could be parsed.
    #[serde(default)]
    pub healed: bool,
    pub state: ToolCallState,
    /// The result text the model sees, including failure text.
    #[serde(default)]
    pub output: Option<String>,
    /// Why the call failed or was refused, for clients.
    #[serde(default)]
    pub error: Option<ErrorReport>,
    /// An opaque provider token that must accompany this call when the
    /// conversation is sent back to the same provider.
    #[serde(default)]
    pub signature: Option<String>,
    /// How an output rule reduced `output` before the model saw it.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reduction: Option<OutputReduction>,
}

/// How an output rule reduced a tool result. The reduced text is the call's
/// `output`; the original is not kept.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct OutputReduction {
    /// The id of the rule that applied.
    pub rule: String,
    /// The rule came from the user's output rules rather than shipping with
    /// the application.
    pub user_rule: bool,
    /// The size of the result before the rule applied.
    pub original_bytes: u64,
    /// The rule's named counts over the lines the model is shown.
    #[serde(default)]
    pub counts: Vec<OutputCount>,
}

/// One named count an output rule reported.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct OutputCount {
    pub name: String,
    pub count: u64,
}

/// A pending request for the user to approve one tool call. It is bound to
/// the call's ID and argument digest and expires when the run ends.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ApprovalRequest {
    /// Generated by the gateway; never shown to the model.
    pub id: Id,
    /// The message holding the call.
    pub message: Id,
    pub call: String,
    pub tool: String,
    pub arguments: String,
    pub digest: String,
    /// Capabilities the tool uses, all within the conversation's grant.
    pub capabilities: BTreeSet<Capability>,
    pub requested_at: u64,
}

/// The user's answer to an [`ApprovalRequest`].
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ApprovalDecision {
    Approve,
    Deny,
}

/// How an approval request ended.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ApprovalOutcome {
    Approved,
    Denied,
    /// The run was cancelled or ended before the user answered.
    Expired,
    /// The tool's permission or the conversation's grant was withdrawn while
    /// the request was waiting; the call did not run.
    Revoked,
}

/// A tool a conversation could use, with how its permission was decided.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ToolOffer {
    pub name: String,
    pub description: String,
    pub capabilities: BTreeSet<Capability>,
    /// The tool host's own policy (for example an MCP server entry).
    pub host_permission: ToolPermission,
    /// The user's setting for this conversation; unset means deny.
    pub permission: Option<ToolPermission>,
    /// What the gateway enforces: the most restrictive of the above, the
    /// parent conversation's and the capability grant.
    pub effective: ToolPermission,
    /// Capabilities the tool needs that this conversation does not have.
    pub missing: BTreeSet<Capability>,
}

/// The tools a conversation could use and the hosts that could not list theirs.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ToolList {
    pub tools: Vec<ToolOffer>,
    pub unavailable: Vec<UnavailableTools>,
}
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct UnavailableTools {
    /// The host or server that failed, as it names itself.
    pub source: String,
    pub error: ErrorReport,
}
